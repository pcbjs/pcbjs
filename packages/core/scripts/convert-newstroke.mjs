// Converts newstroke_font.cpp from Vladimir Uryvaev's newstroke-font.tgz, CC0 1.0, into packages/core/src/fonts/newstroke.ts.
// Usage: node packages/core/scripts/convert-newstroke.mjs <newstroke_font.cpp> > packages/core/src/fonts/newstroke.ts
// packages/core/src/fonts/SOURCES.md has the source, its checksum and the licence.
import { readFileSync } from 'node:fs'

const src = readFileSync(process.argv[2], 'latin1')
const start = src.indexOf('newstroke_font[]')
const table = []
for (const line of src.slice(start, src.indexOf('};', start)).split('\n')) {
  const m = line.match(/^\s*"((?:[^"\\]|\\.)*)"/)
  if (m) table.push(m[1].replace(/\\(.)/g, '$1'))
}
// the array starts at U+0020 and runs on without gaps
const at = cp => table[cp - 0x20]
// the placeholder box upstream draws for a code point it has no glyph for
const BOX = 'F^K[KFYFY[K['
// KiCad 6 and later draw the tilde 11 units lower, at the middle of the x-height, than the 2010 upstream data; pcbjs follows KiCad
const FIX = { 0x7e: s => s.slice(0, 2) + [...s.slice(2)].map((c, i) => (i % 2 && c !== 'R' ? String.fromCharCode(c.charCodeAt(0) + 11) : c)).join('') }

/** [advance, x1, y1, ...] in font units, y up from the baseline, -1, -1 lifting the pen. */
function decode(s) {
  const x0 = s.charCodeAt(0) - 82,
    x1 = s.charCodeAt(1) - 82
  const out = [x1 - x0]
  for (let i = 2; i + 1 < s.length; i += 2) {
    if (s[i] === ' ' && s[i + 1] === 'R') {
      out.push(-1, -1)
      continue
    }
    const x = s.charCodeAt(i) - 82 - x0,
      y = 9 - (s.charCodeAt(i + 1) - 82)
    if (x === -1 && y === -1) throw new Error(`vertex -1, -1 in ${JSON.stringify(s)}`)
    out.push(x, y)
  }
  return out
}
const glyph = cp => {
  let s = at(cp)
  if (s === undefined || s === BOX || s.length < 2) return null
  if (FIX[cp]) s = FIX[cp](s)
  return decode(s)
}
const show = cp => JSON.stringify(String.fromCodePoint(cp)).replace(/[\u007f-￿]/g, c => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)

const extra = []
for (let c = 0xa0; c <= 0x17f; c++) extra.push(c)
for (let c = 0x391; c <= 0x3c9; c++) extra.push(c)
for (let c = 0x2010; c <= 0x2027; c++) extra.push(c)
extra.push(0x2030, 0x20ac, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x221e, 0x2248, 0x2260, 0x2264, 0x2265)

const lines = []
lines.push(`// NewStroke, the single-stroke font KiCad draws its text in, by Vladimir Uryvaev: ASCII, Latin-1, Latin Extended-A, Greek and
// a few symbols. Generated by packages/core/scripts/convert-newstroke.mjs; do not edit by hand.
//
// Source: newstroke_font.cpp in newstroke-font.tgz from the author's page http://vovanium.ru/sledy/newstroke/en, fetched
// 2026-10-26. The author released NewStroke under CC0 1.0, http://creativecommons.org/publicdomain/zero/1.0/, as its README and
// the page say. KiCad builds the same data into common/newstroke_font.cpp; packages/core/src/fonts/SOURCES.md and docs/fonts.md
// have the comparison and the one change, the tilde lowered to where KiCad 6 and later draw it.
//
// Encoding as hershey-simplex.ts: one array per glyph, \`[advance, x1, y1, x2, y2, ...]\` in font units, -1, -1 lifting the pen,
// x right from the glyph's left edge, y UP from the baseline at 0. KiCad's glyph size is 21 units: caps span y = 0 to 21, so
// the cap height is the KiCad text height. Advances include KiCad's spacing between glyphs.

/** Cap height of NewStroke in font units, KiCad's glyph size. */
export const NEWSTROKE_CAP = 21
`)
lines.push('/** Glyphs for ASCII 32 (space) to 126 (tilde), index = code - 32. */')
lines.push('export const NEWSTROKE: readonly (readonly number[])[] = [')
for (let c = 0x20; c <= 0x7e; c++) lines.push(`  /* ${show(c).padEnd(4)} */ [${glyph(c).join(',')}],`)
lines.push(']', '')
lines.push('/** Glyphs beyond ASCII, by character. */')
lines.push('export const NEWSTROKE_EXTRA: Readonly<Record<string, readonly number[]>> = {')
for (const c of extra) {
  const g = glyph(c)
  if (g) lines.push(`  ${show(c)}: [${g.join(',')}],`)
}
lines.push('}', '')
lines.push(`/** Characters drawn with another glyph: the ohm sign is the capital omega, as in KiCad; tab is a space. */
export const NEWSTROKE_ALIAS: Readonly<Record<string, string>> = { '\\u2126': '\\u03a9', '\\t': ' ' }`)
process.stdout.write(lines.join('\n') + '\n')
